// Get all districts for a selected province
export function getDistricts(provinceId: number): District[] {
  const province = nepalData.find((p) => p.id === provinceId);
  return province ? province.districts : [];
}

// Get all local levels for a selected district
export function getLocalLevels(provinceId: number, districtId: string): LocalLevel[] {
  const districts = getDistricts(provinceId);
  const district = districts.find((d) => d.id === districtId);
  return district ? district.localLevels : [];
}

// Get all wards for a selected local level
export function getWards(provinceId: number, districtId: string, localLevelId: string): Ward[] {
  const localLevels = getLocalLevels(provinceId, districtId);
  const localLevel = localLevels.find((l) => l.id === localLevelId);
  return localLevel ? localLevel.wards : [];
}